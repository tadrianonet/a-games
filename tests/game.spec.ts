import {test,expect} from '@playwright/test'
test('menu, movement, collection, jump, pause, persistence and album',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/');await expect(page.getByRole('heading',{name:'Agnes e o Reino das Estrelas'})).toBeVisible()
 await page.screenshot({path:'test-results/menu.png',fullPage:true})
 await page.getByRole('button',{name:'Começar aventura'}).click()
 await expect(page.locator('canvas')).toBeVisible();await page.waitForTimeout(1800)
 await page.keyboard.down('ArrowRight');await page.waitForTimeout(540);await page.keyboard.up('ArrowRight')
 await expect(page.locator('.hud-right')).toContainText('1')
 await page.keyboard.down('ArrowRight');await page.keyboard.down('ArrowUp');await page.waitForTimeout(650);await page.keyboard.up('ArrowUp');await page.keyboard.up('ArrowRight')
 await page.waitForTimeout(500);await page.screenshot({path:'test-results/game.png'})
 await page.getByRole('button',{name:'Pausar',exact:true}).click();await expect(page.getByText('Até as estrelas descansam.')).toBeVisible()
 await page.getByRole('button',{name:'Voltar ao início'}).click()
 await page.reload();await expect(page.getByRole('button',{name:'Continuar aventura'})).toBeVisible()
 await page.getByRole('button',{name:'Meu álbum'}).click();await expect(page.getByText(/de 45 estrelas/)).not.toContainText('0 de 45')
 expect(errors).toEqual([])
})
test('tablet multitouch, released pointers, portrait guidance',async({browser})=>{
 const context=await browser.newContext({viewport:{width:1024,height:768},hasTouch:true,isMobile:true})
 const page=await context.newPage();await page.goto('/');await page.getByRole('button',{name:'Começar aventura'}).click();await page.waitForTimeout(1600)
 const right=page.getByRole('button',{name:'Direita',exact:true});const jump=page.getByRole('button',{name:'Pular',exact:true})
 const r=await right.boundingBox(),j=await jump.boundingBox();if(!r||!j)throw new Error('Controles não renderizados')
 const cdp=await context.newCDPSession(page)
 const points=[{x:r.x+r.width/2,y:r.y+r.height/2,id:1},{x:j.x+j.width/2,y:j.y+j.height/2,id:2}]
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:points});await page.waitForTimeout(500)
 await cdp.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]})
 await expect(page.locator('canvas')).toBeVisible();await page.setViewportSize({width:768,height:1024});await expect(page.getByText('Vire o tablet para brincar')).toBeVisible();await context.close()
})
test('service worker caches game for offline reload',async({browser})=>{
 const context=await browser.newContext();const page=await context.newPage();await page.goto('/')
 await page.evaluate(async()=>{await navigator.serviceWorker.ready});await page.reload();await page.waitForTimeout(1500)
 await context.setOffline(true);await page.reload();await expect(page.getByRole('button',{name:'Começar aventura'})).toBeVisible()
 await page.getByRole('button',{name:'Começar aventura'}).click();await expect(page.locator('canvas')).toBeVisible();await page.waitForTimeout(1000)
 expect(await page.locator('canvas').evaluate((c:HTMLCanvasElement)=>c.width)).toBe(960);await context.close()
})
